-- 톤 노출 순서
--
-- 실사 → 일상 스냅 → 화보 → 시네마틱 → 3D 캐릭터 → 애니.
-- 가까운 사진부터 먼 그림체로 간다. 성별별 사진(tone/male · tone/neutral)은
-- thumbnail_path(tone/<n>)로 짝을 찾아서 순서만 바꿔도 세 성별이 같이 따라온다.
-- id·thumbnail_path는 그대로다 — 이미 만든 캐릭터의 tone_id가 가리키는 행이 바뀌지 않는다.

update public.character_options as o
   set sort_order = v.sort_order
  from (values
    ('a1111111-0000-4000-8000-000000000001', 1),  -- 실사
    ('a1111111-0000-4000-8000-000000000004', 2),  -- 일상 스냅
    ('a1111111-0000-4000-8000-000000000003', 3),  -- 화보
    ('a1111111-0000-4000-8000-000000000002', 4),  -- 시네마틱
    ('a1111111-0000-4000-8000-000000000006', 5),  -- 3D 캐릭터
    ('a1111111-0000-4000-8000-000000000005', 6)   -- 애니
  ) as v(id, sort_order)
 where o.id = v.id::uuid;
